function makeT(lang) {
  const d = STRINGS[lang] || STRINGS.tr;
  return (k, ...args) => {
    let v = d[k];
    if (v === undefined) v = STRINGS.en[k];
    if (v === undefined) return k;
    return typeof v === 'function' ? v(...args) : v;
  };
}
function localeOf(lang) { return lang === 'tr' ? 'tr-TR' : 'en-US'; }

Object.assign(window, { STRINGS, makeT, localeOf });
